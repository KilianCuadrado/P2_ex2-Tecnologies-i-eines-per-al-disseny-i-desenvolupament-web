function buildCovers(folder: string) {
  const encoded = encodeURIComponent(folder);
  const cover400 = `/${encoded}/cover-400.webp`;
  const cover800 = `/${encoded}/cover-800.webp`;
  const cover1200 = `/${encoded}/cover-1200.webp`;
  return {
    cover400,
    cover800,
    cover1200,
    srcset: `${cover400} 400w, ${cover800} 800w, ${cover1200} 1200w`,
  };
}

